package com.shortener.orchestration.agents;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.node.ObjectNode;
import org.springframework.stereotype.Component;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Optional;

/**
 * Generates tests for the implementation output and produces the test-report artifact
 * consumed by the TestGate. In simulated mode (Maven tool disabled) results are
 * deterministic; with the Maven tool enabled the gate re-verifies with a real `mvn test`.
 */
@Component
public class TestAgent implements Agent {

    private final ObjectMapper objectMapper;

    public TestAgent(ObjectMapper objectMapper) {
        this.objectMapper = objectMapper;
    }

    @Override
    public String name() {
        return "test";
    }

    @Override
    public AgentResult execute(AgentContext context) throws AgentExecutionException {
        String requirement = context.run().getRequirementText();
        if (AgentTextUtils.hasMarker(requirement, "fallback-testing")) {
            // Injected unrecoverable failure: exercises the fallback path end-to-end.
            throw new AgentExecutionException(
                    "Test generation failed irrecoverably (injected for fallback demonstration)", false);
        }

        String feature = AgentTextUtils.featureName(requirement);
        Path testDir = context.stageWorkspace().resolve("src");
        Path testFile = testDir.resolve(feature + "ServiceTest.java");
        try {
            Files.createDirectories(testDir);
            Files.writeString(testFile, testSource(feature));
        } catch (IOException exception) {
            throw new AgentExecutionException(
                    "Could not write generated tests: " + exception.getMessage(), true, exception);
        }

        ObjectNode report = objectMapper.createObjectNode();
        report.put("generated", 1);
        report.put("executed", "simulated");
        report.put("passed", 12);
        report.put("failed", 0);
        report.put("coverage", 0.87);
        report.put("notes", "Deterministic simulated run; TestGate re-verifies with Maven when enabled");

        String relative = context.runWorkspace().relativize(testFile).toString().replace('\\', '/');
        return new AgentResult("test-report", report.toPrettyString(),
                List.of("Generated unit tests for " + feature + "Service",
                        "Recorded simulated execution: 12 passed, 0 failed, 87% coverage"),
                List.of(relative));
    }

    @Override
    public Optional<AgentResult> fallback(AgentContext context) {
        // Per design: @Disabled skeletons with reason. The TestGate will then fail the
        // pipeline safely — untested code must not pass release readiness.
        try {
            String feature = AgentTextUtils.featureName(context.run().getRequirementText());
            Path testDir = context.stageWorkspace().resolve("src");
            Files.createDirectories(testDir);
            Path skeleton = testDir.resolve(feature + "ServiceTest.java");
            Files.writeString(skeleton, """
                    package com.shortener.generated;

                    import org.junit.jupiter.api.Disabled;
                    import org.junit.jupiter.api.Test;

                    @Disabled("Test agent exhausted retries — skeleton only, human completion required")
                    class %sServiceTest {

                        @Test
                        void pendingHumanCompletion() {
                        }
                    }
                    """.formatted(feature));
            ObjectNode report = objectMapper.createObjectNode();
            report.put("generated", 1);
            report.put("executed", "skipped");
            report.put("passed", 0);
            report.put("failed", 0);
            report.put("coverage", 0.0);
            report.put("notes", "Fallback skeleton with @Disabled; coverage gate will stop the pipeline");
            return Optional.of(AgentResult.of("test-report", report.toPrettyString(),
                    List.of("Fallback: emitted @Disabled test skeletons with documented reason")));
        } catch (IOException exception) {
            return Optional.empty();
        }
    }

    @Override
    public void rollback(AgentContext context) {
        ImplementationAgent.deleteRecursively(context.stageWorkspace());
    }

    private String testSource(String feature) {
        return """
                package com.shortener.generated;

                import org.junit.jupiter.api.Test;

                import static org.junit.jupiter.api.Assertions.assertEquals;

                /** Generated by TestAgent. */
                class %sServiceTest {

                    @Test
                    void describeReturnsFeatureName() {
                        assertEquals("%s", new %sService().describe());
                    }
                }
                """.formatted(feature, feature, feature);
    }
}
